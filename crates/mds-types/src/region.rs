/// Двухуровневая геопривязка из текста: возвращает `region` (субъект РФ) и `place` (город или район).
pub fn geo_in(text: &str) -> GeoTag {
    let hay = fold(text);
    let subject = best(&hay, SUBJECTS);
    let district = best_place_phrase(&hay, DISTRICTS_AND_PLACES, subject);
    let city = best_city(&hay, subject);

    match (subject, district, city) {
        (Some(reg), _, _) => {
            let final_place = best_place_phrase(&hay, DISTRICTS_AND_PLACES, Some(reg))
                .map(|row| row.0)
                .filter(|p| *p != reg)
                .or_else(|| {
                    best_city(&hay, Some(reg))
                        .map(|row| row.0)
                        .filter(|p| *p != reg)
                });
            GeoTag {
                region: Some(reg),
                place: final_place,
            }
        }
        (None, Some((d_place, d_reg, _, _)), Some((c_place, c_reg, _, _))) => {
            if d_reg == c_reg && d_place != d_reg {
                GeoTag {
                    region: Some(d_reg),
                    place: Some(d_place),
                }
            } else if d_place.contains("район") {
                GeoTag {
                    region: Some(d_reg),
                    place: Some(d_place),
                }
            } else {
                GeoTag {
                    region: Some(c_reg),
                    place: if c_place == c_reg { None } else { Some(c_place) },
                }
            }
        }
        (None, Some((place, place_reg, _, _)), None) | (None, None, Some((place, place_reg, _, _))) => GeoTag {
            region: Some(place_reg),
            place: if place == place_reg { None } else { Some(place) },
        },
        (None, None, None) => GeoTag::default(),
    }
}

/// Двухуровневая геопривязка с учётом адреса страницы (поддомен или папка `/spb/`).
pub fn geo_for_page(url: &str, text: &str) -> GeoTag {
    let mut tag = geo_in(text);
    if tag.region.is_none() {
        let from_url = geo_from_url(url);
        if from_url.region.is_some() {
            tag = from_url;
        }
    }
    tag
}

fn geo_from_url(url: &str) -> GeoTag {
    let lower = url.to_ascii_lowercase();
    let Some((_, rest)) = lower.split_once("://") else {
        return GeoTag::default();
    };
    let host_and_path = rest.split(['?', '#']).next().unwrap_or(rest);
    let (host, path) = host_and_path.split_once('/').unwrap_or((host_and_path, ""));
    let host = host.split(':').next().unwrap_or(host).trim_start_matches("www.");
    if let Some((sub, _)) = host.split_once('.') {
        if let Some((_, region, place)) = URL_GEO.iter().find(|(code, _, _)| *code == sub) {
            return GeoTag {
                region: Some(region),
                place: *place,
            };
        }
    }
    let first_seg = path.split('/').find(|seg| !seg.is_empty()).unwrap_or("");
    if let Some((_, region, place)) = URL_GEO.iter().find(|(code, _, _)| *code == first_seg) {
        return GeoTag {
            region: Some(region),
            place: *place,
        };
    }
    GeoTag::default()
}

pub fn region_in(text: &str) -> Option<&'static str> {
    geo_in(text).region
}

pub fn place_in(text: &str) -> Option<&'static str> {
    geo_in(text).place
}

pub fn canonical_region(value: &str) -> Option<&'static str> {
    let folded = fold(value.trim());
    if folded.is_empty() {
        return None;
    }
    region_names()
        .iter()
        .copied()
        .find(|name| fold(name) == folded)
        .or_else(|| region_in(value))
}

pub fn is_geo_word(token: &str) -> bool {
    let folded = fold(token.trim());
    if folded.chars().count() < 3 {
        return false;
    }
    if matches!(
        folded.as_str(),
        "область"
            | "области"
            | "обл"
            | "район"
            | "района"
            | "районе"
            | "край"
            | "края"
            | "крае"
            | "республика"
            | "республики"
            | "округ"
            | "округа"
            | "город"
            | "городе"
    ) {
        return true;
    }
    CITIES
        .iter()
        .any(|(needle, _, _)| !needle.contains(' ') && city_word(&folded, needle))
}

pub fn region_names() -> &'static [&'static str] {
    use std::sync::OnceLock;
    static NAMES: OnceLock<Vec<&'static str>> = OnceLock::new();
    NAMES.get_or_init(|| {
        let mut names: Vec<&str> = SUBJECTS.iter().map(|row| row.1).collect();
        names.push("Москва");
        names.sort();
        names.dedup();
        names
    })
    .as_slice()
}

fn best<'a>(hay: &str, rows: &'a [(&str, &str)]) -> Option<&'a str> {
    let mut scored: Vec<(&str, usize, usize)> = Vec::new();
    for (needle, canonical) in rows {
        let hits = occurs(hay, needle);
        if hits.is_empty() {
            continue;
        }
        if let Some(slot) = scored.iter_mut().find(|row| row.0 == *canonical) {
            slot.1 += hits.len();
            slot.2 = slot.2.min(hits[0]);
        } else {
            scored.push((*canonical, hits.len(), hits[0]));
        }
    }
    scored.sort_by(|left, right| right.1.cmp(&left.1).then(left.2.cmp(&right.2)));
    scored.first().map(|row| row.0)
}

fn best_place_phrase<'a>(
    hay: &str,
    rows: &'a [(&str, &str, &str)],
    only_region: Option<&str>,
) -> Option<(&'a str, &'a str, usize, usize)> {
    let mut scored: Vec<(&str, &str, usize, usize)> = Vec::new();
    for (needle, place, region) in rows {
        if let Some(req) = only_region {
            if *region != req {
                continue;
            }
        }
        let hits = occurs(hay, needle);
        if hits.is_empty() {
            continue;
        }
        if let Some(slot) = scored.iter_mut().find(|row| row.0 == *place && row.1 == *region) {
            slot.2 += hits.len();
            slot.3 = slot.3.min(hits[0]);
        } else {
            scored.push((*place, *region, hits.len(), hits[0]));
        }
    }
    scored.sort_by(|left, right| right.2.cmp(&left.2).then(left.3.cmp(&right.3)));
    scored.first().copied()
}

fn best_city(
    hay: &str,
    only_region: Option<&str>,
) -> Option<(&'static str, &'static str, usize, usize)> {
    let mut scored: Vec<(&'static str, &'static str, usize, usize)> = Vec::new();
    let mut offset = 0;
    for word in hay.split(|ch: char| !ch.is_alphabetic() && ch != '-') {
        if word.is_empty() {
            continue;
        }
        let start = hay[offset..].find(word).map(|pos| offset + pos).unwrap_or(offset);
        offset = start + word.len();
        for (needle, place, region) in CITIES {
            if let Some(req) = only_region {
                if *region != req {
                    continue;
                }
            }
            if needle.contains(' ') || !city_word(word, needle) {
                continue;
            }
            if let Some(slot) = scored.iter_mut().find(|row| row.0 == *place && row.1 == *region) {
                slot.2 += 1;
                slot.3 = slot.3.min(start);
            } else {
                scored.push((*place, *region, 1, start));
            }
        }
    }
    scored.sort_by(|left, right| right.2.cmp(&left.2).then(left.3.cmp(&right.3)));
    scored.first().copied()
}

fn city_word(word: &str, needle: &str) -> bool {
    if word == needle {
        return true;
    }
    let word: Vec<char> = word.chars().collect();
    let needle: Vec<char> = needle.chars().collect();
    if needle.len() < 4 || word.len() + 1 < needle.len() || word.len() > needle.len() + 2 {
        return false;
    }
    let Some(last) = word.last().copied() else {
        return false;
    };
    if !"аеиоуыэюяйь".contains(last) {
        return false;
    }
    if word.len() >= needle.len() && word[..needle.len()] == needle[..] {
        return true;
    }
    let prefix = needle.len() - 1;
    word.len() >= prefix && word[..prefix] == needle[..prefix]
}

fn occurs(hay: &str, needle: &str) -> Vec<usize> {
    let mut from = 0;
    let mut hits = Vec::new();
    while let Some(pos) = hay[from..].find(needle) {
        let start = from + pos;
        let end = start + needle.len();
        if edged(hay, start, end) {
            hits.push(start);
        }
        from = end;
    }
    hits
}

fn edged(hay: &str, start: usize, end: usize) -> bool {
    let before = hay[..start].chars().next_back().map(|ch| ch.is_alphabetic()).unwrap_or(false);
    let after = hay[end..].chars().next().map(|ch| ch.is_alphabetic()).unwrap_or(false);
    !before && !after
}

fn fold(text: &str) -> String {
    text.to_lowercase().replace('ё', "е")
}

/// Расстояние по поверхности Земли в километрах (формула гаверсинуса).
pub fn haversine_km(lat1: f64, lon1: f64, lat2: f64, lon2: f64) -> f64 {
    const EARTH_KM: f64 = 6371.0;
    let dlat = (lat2 - lat1).to_radians();
    let dlon = (lon2 - lon1).to_radians();
    let lat1 = lat1.to_radians();
    let lat2 = lat2.to_radians();
    let a = (dlat * 0.5).sin().powi(2) + lat1.cos() * lat2.cos() * (dlon * 0.5).sin().powi(2);
    let c = 2.0 * a.clamp(0.0, 1.0).sqrt().asin();
    EARTH_KM * c
}

pub fn valid_coords(lat: f64, lon: f64) -> bool {
    lat.is_finite()
        && lon.is_finite()
        && (-90.0..=90.0).contains(&lat)
        && (-180.0..=180.0).contains(&lon)
        && (lat.abs() > 0.01 || lon.abs() > 0.01)
}

/// Находит маркер `Geo: lat, lon` или `координаты: lat, lon` в тексте страницы или `/llms.txt`.
pub fn coords_in_text(text: &str) -> Option<(f64, f64)> {
    for line in text.lines() {
        let lower = line.trim().to_lowercase();
        for prefix in ["geo:", "координаты:", "location:"] {
            if let Some(rest) = lower.strip_prefix(prefix) {
                if let Some(pair) = parse_lat_lon_pair(rest) {
                    return Some(pair);
                }
            }
        }
    }
    let lower = text.to_lowercase();
    for needle in ["geo:", "координаты:"] {
        if let Some(pos) = lower.find(needle) {
            let tail = &lower[pos + needle.len()..];
            let slice: String = tail.chars().take(48).collect();
            if let Some(pair) = parse_lat_lon_pair(&slice) {
                return Some(pair);
            }
        }
    }
    None
}

pub fn parse_lat_lon_pair(raw: &str) -> Option<(f64, f64)> {
    let cleaned: String = raw
        .trim()
        .chars()
        .take_while(|ch| ch.is_ascii_digit() || matches!(*ch, '.' | '-' | '+' | ',' | ';' | ' ' | '\t'))
        .collect();
    let mut nums = cleaned
        .split([',', ';', ' ', '\t'])
        .filter(|part| !part.is_empty())
        .filter_map(|part| part.parse::<f64>().ok());
    let first = nums.next()?;
    let second = nums.next()?;
    if valid_coords(first, second) {
        Some((first, second))
    } else {
        None
    }
}

fn cut(text: &str, start: usize, end: usize) -> &str {
    let end = end.min(text.len());
    let start = start.min(end);
    let start = (0..=start).rev().find(|at| text.is_char_boundary(*at)).unwrap_or(0);
    let end = (end..=text.len()).find(|at| text.is_char_boundary(*at)).unwrap_or(text.len());
    &text[start..end]
}

/// Извлекает координаты из ссылок и виджетов Яндекс.Карт, Google Maps и OpenStreetMap в HTML.
pub fn coords_in_html_maps(html: &str) -> Option<(f64, f64)> {
    let lower = html.to_ascii_lowercase();
    // Яндекс.Карты: ll=lon,lat или ll=lon%2clat или pt=lon,lat (в Яндексе долгота идёт первой!)
    for marker in ["ll=", "pt="] {
        let mut from = 0;
        while let Some(rel) = lower[from..].find(marker) {
            let start = from + rel + marker.len();
            from = start;
            let window = cut(&lower, start.saturating_sub(120), start + 80);
            if !(window.contains("yandex.") || window.contains("ya.ru") || window.contains("api-maps")) {
                continue;
            }
            let tail = cut(&lower, start, start + 48);
            let decoded = tail.replace("%2c", ",");
            if let Some((lon, lat)) = parse_lat_lon_pair(&decoded) {
                if valid_coords(lat, lon) {
                    return Some((lat, lon));
                }
            }
        }
    }
    // Google Maps: !3dLAT!4dLON или @LAT,LON
    if let Some(d3) = lower.find("!3d") {
        let rest = cut(&lower, d3 + 3, d3 + 60);
        if let Some((lat_str, after)) = rest.split_once("!4d") {
            let lon_str: String = after
                .chars()
                .take_while(|ch| ch.is_ascii_digit() || matches!(*ch, '.' | '-' | '+'))
                .collect();
            if let (Ok(lat), Ok(lon)) = (lat_str.parse::<f64>(), lon_str.parse::<f64>()) {
                if valid_coords(lat, lon) {
                    return Some((lat, lon));
                }
            }
        }
    }
    for host_hint in ["google.com/maps", "maps.google."] {
        if let Some(pos) = lower.find(host_hint) {
            let slice = cut(&lower, pos, pos + 200);
            if let Some(at) = slice.find('@') {
                if let Some(pair) = parse_lat_lon_pair(&slice[at + 1..]) {
                    return Some(pair);
                }
            }
        }
    }
    // OpenStreetMap: mlat=LAT&mlon=LON
    if let Some(mlat) = lower.find("mlat=") {
        let slice = cut(&lower, mlat + 5, mlat + 64);
        let lat_str: String = slice
            .chars()
            .take_while(|ch| ch.is_ascii_digit() || matches!(*ch, '.' | '-' | '+'))
            .collect();
        if let Some(mlon) = slice.find("mlon=") {
            let lon_str: String = slice[mlon + 5..]
                .chars()
                .take_while(|ch| ch.is_ascii_digit() || matches!(*ch, '.' | '-' | '+'))
                .collect();
            if let (Ok(lat), Ok(lon)) = (lat_str.parse::<f64>(), lon_str.parse::<f64>()) {
                if valid_coords(lat, lon) {
                    return Some((lat, lon));
                }
            }
        }
    }
    None
}

