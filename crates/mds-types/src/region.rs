pub fn region_in(text: &str) -> Option<&'static str> {
    let hay = fold(text);
    best(&hay, SUBJECTS).or_else(|| best_city(&hay))
}

pub fn canonical_region(value: &str) -> Option<&'static str> {
    let folded = fold(value.trim());
    if folded.is_empty() {
        return None;
    }
    region_names()
        .iter()
        .copied()
        .find(|name| fold(name) == folded)
        .or_else(|| region_in(value))
}

pub fn region_names() -> &'static [&'static str] {
    use std::sync::OnceLock;
    static NAMES: OnceLock<Vec<&'static str>> = OnceLock::new();
    NAMES.get_or_init(|| {
        let mut names: Vec<&str> = SUBJECTS.iter().map(|row| row.1).collect();
        names.push("Москва");
        names.sort();
        names.dedup();
        names
    })
    .as_slice()
}

fn best<'a>(hay: &str, rows: &'a [(&str, &str)]) -> Option<&'a str> {
    let mut scored: Vec<(&str, usize, usize)> = Vec::new();
    for (needle, canonical) in rows {
        let hits = occurs(hay, needle);
        if hits.is_empty() {
            continue;
        }
        if let Some(slot) = scored.iter_mut().find(|row| row.0 == *canonical) {
            slot.1 += hits.len();
            slot.2 = slot.2.min(hits[0]);
        } else {
            scored.push((*canonical, hits.len(), hits[0]));
        }
    }
    scored.sort_by(|left, right| right.1.cmp(&left.1).then(left.2.cmp(&right.2)));
    scored.first().map(|row| row.0)
}

fn best_city(hay: &str) -> Option<&'static str> {
    let mut scored: Vec<(&str, usize, usize)> = Vec::new();
    let mut offset = 0;
    for word in hay.split(|ch: char| !ch.is_alphabetic()) {
        if word.is_empty() {
            continue;
        }
        let start = hay[offset..].find(word).map(|pos| offset + pos).unwrap_or(offset);
        offset = start + word.len();
        for (needle, canonical) in CITIES {
            if !city_word(word, needle) {
                continue;
            }
            if let Some(slot) = scored.iter_mut().find(|row| row.0 == *canonical) {
                slot.1 += 1;
                slot.2 = slot.2.min(start);
            } else {
                scored.push((*canonical, 1, start));
            }
        }
    }
    scored.sort_by(|left, right| right.1.cmp(&left.1).then(left.2.cmp(&right.2)));
    scored.first().map(|row| row.0)
}

fn city_word(word: &str, needle: &str) -> bool {
    if word == needle {
        return true;
    }
    let word: Vec<char> = word.chars().collect();
    let needle: Vec<char> = needle.chars().collect();
    if needle.len() < 4 || word.len() + 1 < needle.len() || word.len() > needle.len() + 2 {
        return false;
    }
    let Some(last) = word.last().copied() else {
        return false;
    };
    if !"аеиоуыэюяйь".contains(last) {
        return false;
    }
    if word.len() >= needle.len() && word[..needle.len()] == needle[..] {
        return true;
    }
    let prefix = needle.len() - 1;
    word.len() >= prefix && word[..prefix] == needle[..prefix]
}

fn occurs(hay: &str, needle: &str) -> Vec<usize> {
    let mut from = 0;
    let mut hits = Vec::new();
    while let Some(pos) = hay[from..].find(needle) {
        let start = from + pos;
        let end = start + needle.len();
        if edged(hay, start, end) {
            hits.push(start);
        }
        from = end;
    }
    hits
}

fn edged(hay: &str, start: usize, end: usize) -> bool {
    let before = hay[..start].chars().next_back().map(|ch| ch.is_alphabetic()).unwrap_or(false);
    let after = hay[end..].chars().next().map(|ch| ch.is_alphabetic()).unwrap_or(false);
    !before && !after
}

fn fold(text: &str) -> String {
    text.to_lowercase().replace('ё', "е")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn oblast_beats_a_delivery_city() {
        let text = "Завод стеклянных банок. Отгрузка по России, доставка в Москву. Волгоградская область, Камышин.";
        assert_eq!(region_in(text), Some("Волгоградская область"));
    }

    #[test]
    fn city_alone_marks_its_oblast() {
        assert_eq!(region_in("Производитель банок, Камышин"), Some("Волгоградская область"));
        assert_eq!(region_in("Пасека в Орле"), Some("Орловская область"));
    }

    #[test]
    fn moscow_oblast_is_not_the_city() {
        assert_eq!(region_in("Склад, Московская область"), Some("Московская область"));
        assert_eq!(region_in("Офис в Москве"), Some("Москва"));
    }

    #[test]
    fn page_without_a_place_has_no_region() {
        assert_eq!(region_in("стеклянные банки оптом"), None);
    }
}
